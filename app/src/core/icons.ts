const outline = (id: string): string => `${id}-outline`;

export const ICON_GROUPS: { name: string; icons: string[] }[] = GROUPS.map((g) => ({
  name: g.name,
  icons: g.ids.split(' ').map(outline),
}));

export const ICON_CHOICES: string[] = [...new Set(ICON_GROUPS.flatMap((g) => g.icons))];

// Which category the picker opens on for each starting point. A nudge, not a restriction.
const PRESET_GROUP: Record<string, string> = {
  'set-plan': 'Move', 'checklist-totals': 'Food', measurement: 'Health', 'time-blocks': 'Time', counter: 'Stats', 'check-in': 'Time',
};

export function groupIndexForPreset(presetId: string): number {
  const i = ICON_GROUPS.findIndex((g) => g.name === PRESET_GROUP[presetId]);
  return i < 0 ? 0 : i;
}

export const DEFAULT_ICON = 'apps-outline';

// Search: every word typed must match the start of a keyword (or of the icon name). Plural and
// "-ing" endings are forgiven, so "lifting", "lifts" and "lift" all find the barbell.
function stem(w: string): string {
  let r = w.length > 4 && w.endsWith('ing') ? w.slice(0, -3) : w.length > 3 && w.endsWith('s') ? w.slice(0, -1) : w;
  if (r.length > 3 && r[r.length - 1] === r[r.length - 2]) r = r.slice(0, -1); // running -> run
  return r;
}

export function searchIcons(query: string): string[] {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return [];
  const scored: { icon: string; score: number }[] = [];
  for (const icon of ICON_CHOICES) {
    const id = icon.replace(/-outline$/, '');
    const keys = [...id.split('-'), ...(K[id] ?? '').split(' ')];
    let score = 0;
    let ok = true;
    for (const raw of words) {
      const w = stem(raw);
      const exact = keys.includes(raw) || keys.includes(w);
      const starts = keys.some((k) => k.startsWith(w) || (k.length >= 4 && w.startsWith(k)) || (w.length >= 4 && w.startsWith(stem(k)) && stem(k).length >= 4));
      if (!exact && !starts) { ok = false; break; }
      score += exact ? 2 : 1;
    }
    if (ok) scored.push({ icon, score });
  }
  return scored.sort((a, b) => b.score - a.score).map((x) => x.icon);
}

